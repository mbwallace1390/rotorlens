/**
 * Strips `constraints { ... }` blocks out of a Gradle build file.
 *
 * A constraint pins the version of something already in the dependency graph. It
 * uses the same `implementation("group:artifact:version")` syntax as a real
 * declaration, so anything reading declarations by pattern sees a version pin as
 * a newly adopted component.
 */
function withoutConstraintBlocks(source) {
  const blockStart = /\bconstraints\s*\{/g;
  let result = '';
  let index = 0;
  let match;

  while ((match = blockStart.exec(source)) !== null) {
    result += source.slice(index, match.index);

    // Walk the braces rather than matching to the next `}`, so a nested block
    // cannot end the skip early.
    let depth = 0;
    let cursor = match.index + match[0].length - 1;
    for (; cursor < source.length; cursor += 1) {
      if (source[cursor] === '{') {
        depth += 1;
      } else if (source[cursor] === '}') {
        depth -= 1;
        if (depth === 0) {
          cursor += 1;
          break;
        }
      }
    }

    index = cursor;
    blockStart.lastIndex = cursor;
  }

  return result + source.slice(index);
}

test('every committed fixture is generated by this project and hash-stable', async () => {
  const manifest = await readJson('fixtures/synthetic/manifest.json');
  assert.equal(manifest.origin, 'generated');
  assert.equal(manifest.thirdPartyMaterial, 'none');
  assert.equal(manifest.containsRealFlightData, false);

  const onDisk = (await readdir(fixtureDir)).filter(name => name !== 'manifest.json');
  assert.deepEqual(
    onDisk.sort(),
    manifest.fixtures.map(fixture => fixture.file).sort(),
    'fixtures/ must contain exactly the generated files listed in the manifest'
  );

  for (const fixture of manifest.fixtures) {
    const bytes = await readFile(path.join(fixtureDir, fixture.file));

    // A checkout that rewrote line endings shows up as a length inflated by
    // exactly the number of newlines. Say so, rather than leaving someone to
    // work out why a committed file changed size on its own.
    if (bytes.length !== fixture.byteLength) {
      const newlines = bytes.filter(byte => byte === 0x0a).length;
      const mangled = bytes.length - fixture.byteLength === newlines;
      assert.fail(
        `${fixture.file} is ${bytes.length} bytes, expected ${fixture.byteLength}` +
        (mangled
          ? '. The difference equals its newline count, so the checkout converted ' +
            'LF to CRLF — .gitattributes should mark logs as binary. Restore with: ' +
            'git rm --cached -r . && git reset --hard'
          : '.')
      );
    }

    assert.equal(sha256Hex(bytes), fixture.sha256, `${fixture.file} hash changed`);
  }
});

