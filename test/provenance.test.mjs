test('the shipping snapshot still covers what the build file declares', async () => {
  // Guards the snapshot against going stale: adding a dependency without
  // regenerating it would otherwise leave the notices checked against an old,
  // passing list.
  const gradle = await readFile(
    path.join(projectRoot, 'android', 'app', 'build.gradle.kts'), 'utf8'
  );
  const snapshot = await readJson('android/shipping-dependencies.json');

  // A `constraints` block pins the version of something already in the graph. It
  // declares nothing, and reading one as a dependency is how this test used to
  // report a version pin as an unattributed component.
  const declarations = withoutConstraintBlocks(gradle);
  const declared = [...declarations.matchAll(
    /implementation\("([^:"]+):([^:"]+):([^"]+)"\)/g
  )].map(match => `${match[1]}:${match[2]}:${match[3]}`);

  assert.ok(declared.length > 0, 'the pattern must still match how deps are declared');

  const shipped = new Set(snapshot.components);

  for (const coordinate of declared) {
    assert.ok(
      shipped.has(coordinate),
      `${coordinate} is declared at a different coordinate than ` +
        'android/shipping-dependencies.json records; ' +
        'regenerate it with `gradlew :app:recordShippingDependencies`'
    );
  }
});

